def make_response(
    request_id: str | None,
    *,
    result: Any = None,
    error: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Build a response and enforce the mutually exclusive success/error shape."""
    if (result is None) == (error is None):
        raise ValueError("exactly one of result or error must be supplied")

    response: dict[str, Any] = {
        "protocol_version": PROTOCOL_VERSION,
        "type": RESPONSE_TYPE,
        "request_id": request_id,
        "ok": error is None,
    }
    if error is None:
        response["result"] = result
    else:
        response["error"] = error
    return response


def make_error(
    request_id: str | None,
    code: str,
    message: str,
    *,
    retryable: bool = False,
    details: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Build a structured protocol error response."""
    return make_response(
        request_id,
        error={
            "code": code,
            "message": message,
            "retryable": retryable,
            "details": details or {},
        },
    )


def make_event(event: str, payload: dict[str, Any]) -> dict[str, Any]:
    """Build a protocol event envelope."""
    return {
        "protocol_version": PROTOCOL_VERSION,
        "type": EVENT_TYPE,
        "event": event,
        "payload": payload,
    }
